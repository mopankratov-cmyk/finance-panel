/**
 * Какую кампанию показывать справа — и когда решение принимать вообще.
 *
 * Вся тонкость в третьем состоянии. Кроме «выбрана эта» и «такой нет» есть
 * «список ещё не приехал», и оно выглядит в точности как «такой нет»: список
 * пуст. Рекламный кабинет грузится двадцать с лишним секунд, всё это время
 * проверка «есть ли выбранная кампания среди строк» отвечала «нет» — и ссылка
 * вида ?campaign=39112979 успевала обнулиться до появления данных, после чего
 * выбор падал на первую строку по расходу, а адрес молча переписывался на неё.
 * Со стороны это выглядело как «ссылки на кампанию не работают вовсе».
 *
 * Такие ссылки строит мост из CTR-тестов: человек идёт останавливать кампанию,
 * которая жжёт бюджет теста, и попадает на самую дорогую активную. Поэтому
 * решение вынесено сюда — под тест, а не в эффект, где его видно только глазами
 * на живом кабинете.
 */
export type CampaignSelectionDecision =
  /** Ничего не менять: данных нет, судить не о чем. */
  | { kind: "wait" }
  /** Ничего не выбрано — открываем первую строку текущего фильтра. */
  | { kind: "select"; campaignId: number | null }
  /** Кампанию назвали явно, но в кабинете её нет. Подменять нельзя — снимаем. */
  | { kind: "clear" }
  /** Выбор остаётся как есть. */
  | { kind: "keep" };

export function decideCampaignSelection(input: {
  /** Все кампании кабинета, без фильтров экрана. */
  allIds: number[];
  /** Кампании, прошедшие фильтры, в порядке показа. */
  visibleIds: number[];
  selectedId: number | null;
}): CampaignSelectionDecision {
  if (input.allIds.length === 0) return { kind: "wait" };
  if (input.selectedId == null) return { kind: "select", campaignId: input.visibleIds[0] ?? null };
  // Проверяем по полному списку, а не по видимому: кампания, выпавшая из
  // фильтра «Активные», из кабинета никуда не делась, и снимать её нельзя —
  // экран показывает такую отдельной строкой над списком.
  if (input.allIds.includes(input.selectedId)) return { kind: "keep" };
  return { kind: "clear" };
}
