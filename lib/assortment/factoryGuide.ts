/** company — юрлицо (有限公司 и т. п.): название и ссылку храним; individual — ИП (个体工商户), unknown — не ясно: только псевдоним и ссылка. */
export type EntityKind = "company" | "individual" | "unknown";

/**
 * Юрлицо или ИП по названию — ОЦЕНКА до проверки в реестре (после неё — тип из 88查): суффикс 公司 (有限公司, 有限责任公司, 股份有限公司,
 * в том числе с пометкой в скобках) — юрлицо; «个体工商户» в названии или типичные вывески ИП (商行, 经营部, 店, 档口, 工作室) — ИП;
 * прочее (…厂, голое имя) — не ясно. У ИП название магазина бывает именем человека, поэтому наружу выходит только у юрлиц.
 */
export function entityFromName(name: string | null | undefined): EntityKind {
  const n = String(name ?? "").normalize("NFKC").replace(/\s+/g, "");
  if (!n) return "unknown";
  if (/个体工商户|个体户/.test(n)) return "individual";
  if (/公司(\([^)]*\))?$/.test(n)) return "company";
  if (/(商行|经营部|批发部|店|档口|工作室|门市部)(\([^)]*\))?$/.test(n)) return "individual";
  return "unknown";
}

