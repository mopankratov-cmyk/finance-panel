/** Провинции кластеров сумок: регистрация вне их — мягкий флаг «спросить, где цех». */
export const BAG_PROVINCES: readonly string[] = ["广东", "河北", "浙江", "福建"];

const stripAdmin = (s: string | null | undefined) => String(s ?? "").normalize("NFKC").replace(/\s+/g, "").replace(/(省|市|自治区|特别行政区)$/, "");

/**
 * Кластер по региону регистрации и названию (оценка): 狮岭 / 花都 — Шилин; 白沟 или город Баодин — Байгоу; прочий Гуанчжоу — оптовые
 * ряды; Цзясин / 平湖 — Пинху; Цюаньчжоу. Регистрация — не цех: фабрика может шить в другом месте.
 */
export function clusterOf(region: { province?: string | null; city?: string | null; hint?: string | null }): FactoryClusterKey | null {
  const city = stripAdmin(region.city);
  const hint = String(region.hint ?? "").normalize("NFKC");
  if (/狮岭|花都/.test(hint) || /狮岭|花都/.test(city)) return "shiling";
  if (/白沟/.test(hint) || city === "保定" || city === "高碑店") return "baigou";
  if (city === "广州") return "guangzhou";
  if (/平湖/.test(hint) || city === "嘉兴" || city === "平湖") return "pinghu";
  if (city === "泉州") return "quanzhou";
  return null;
}

/** Провинция вне кластеров сумок (провинция известна). */
export function outsideBagProvinces(province: string | null | undefined): boolean {
  const p = stripAdmin(province);
  return p.length > 0 && !BAG_PROVINCES.includes(p);
}

