import { constructionHead } from "./collections";

/**
 * Ключ модели каталога (движок тенденций, этап 1): строки обхода → модели.
 *
 * Каталог хранит строку на то, что отдал источник. У части источников это
 * ЦВЕТ или материал модели, а не сама модель: Shopify-бренды (JW PEI, Polène,
 * Songmont, Rains) кладут каждую расцветку отдельным товаром, ASOS и H&M —
 * отдельной карточкой на цвет. Без склейки счётчик «моделей» врёт (на 04.10 у
 * JW PEI 1 225 строк при ~590 моделях) и любая доля формы перекошена одним
 * брендом.
 *
 * У остальных источников (Zara, Uniqlo, сайты РФ) номер строки уже модельный
 * (модель, а не цвет-размер) — их НЕ склеиваем по названию: у сайтов РФ названия
 * общие («куртка женская» у десятков разных моделей), склейка по названию
 * слила бы разные вещи. Ложная склейка хуже незамеченного дубля: она прячет
 * новую форму под старым цветом.
 */
export const COLOR_VARIANT_SOURCES: ReadonlySet<string> = new Set([
  "S014", // Rains (Shopify): расцветка — отдельный товар
  "S024", // Polène (Shopify): «Модель - Материал Цвет»
  "S026", // Songmont (Shopify): расцветки с одним названием
  "S027", // JW PEI (Shopify): «Модель - Цвет»
  "S046", // ASOS: «… in black» — отдельная карточка на цвет; бренд и модель — в названии
  // H&M (S007) НЕ здесь: названия у них общие («Padded jacket» у разных артикулов), и склейка
  // по названию слила бы разные модели — а это хуже незамеченного дубля (по ревью 04.10).
]);

/**
 * Ключ модели. Расцветки одной модели получают один ключ; у остальных источников
 * ключ — сама строка. Ключ не пересекает источники: Mango на ASOS и Mango на
 * своём сайте — отдельная задача (межисточниковая идентичность, этап 2).
 */
export function modelKey(input: { sourceId: string; sourceItemId: string; title: string | null | undefined }): string {
  if (COLOR_VARIANT_SOURCES.has(input.sourceId)) {
    const head = constructionHead(input.title);
    // Название пустое или одно слово-цвет не склеиваем — оставляем строку как есть.
    if (head.length >= 3) return `${input.sourceId}|${head}`;
  }
  return `${input.sourceId}|${input.sourceItemId}`;
}

/**
 * Новые строки обхода → новые МОДЕЛИ. Расцветка уже известной модели — не
 * новинка: иначе каждый новый цвет Polène или JW PEI был бы отдельной «новинкой» в
 * ленте и отдельной находкой, хотя в каталоге модель одна. Две новые расцветки
 * ещё не виденной модели в одном обходе — тоже одна новинка, а не две.
 *
 * `sameModel` — строки, которые ложатся базой (не новинкой): расцветки известной
 * модели и повторы внутри обхода. Источники «одна строка = модель» не затронуты:
 * ключ новой строки у них уникален.
 */
export function newModelsOnly<T>(fresh: readonly T[], keyOf: (item: T) => string, knownKeys: ReadonlySet<string>): { fresh: T[]; sameModel: T[] } {
  const seen = new Set(knownKeys);
  const kept: T[] = [];
  const sameModel: T[] = [];
  for (const item of fresh) {
    const key = keyOf(item);
    if (seen.has(key)) {
      sameModel.push(item);
      continue;
    }
    seen.add(key);
    kept.push(item);
  }
  return { fresh: kept, sameModel };
}
