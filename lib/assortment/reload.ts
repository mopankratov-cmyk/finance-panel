/**
 * Повторное чтение экрана после действия. Чистая функция — одна на подборку и карточку модели.
 *
 * Сбой чтения и сбой действия обычно приходят вместе (обрыв сети, 5xx базы). Если «перечитать» после действия молча
 * подменяет готовый экран строкой ошибки, человек теряет всё, что видел, вместе с сообщением о том, что уже сделано, и повторить нечем.
 * Поэтому «мягкое» чтение (после действия) при сбое оставляет прежний готовый экран, а ошибкой чтения заменяется только начальная загрузка.
 */
export function afterReload<S extends { kind: string }>(prev: S, next: S, soft: boolean): S {
  return soft && next.kind === "error" && prev.kind === "ready" ? prev : next;
}

/**
 * Что сказать в окне после конфликта версии (409), когда карточку перечитали сами. Перечитали — следующая отправка уйдёт со свежей
 * версией, так и пишем; не вышло — конфликт остаётся, и в окне нужна кнопка «Обновить карточку» (без неё «Отклонить» бесконечно шлёт старую).
 */
export function conflictNotice(refreshed: boolean): { message: string; conflict: boolean } {
  return refreshed
    ? { message: "Карточку только что изменили — данные обновлены. Нажмите «Отклонить» ещё раз.", conflict: false }
    : { message: "Карточку только что изменили, а обновить её не получилось — проверьте связь.", conflict: true };
}
