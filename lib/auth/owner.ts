/**
 * Владелец панели — учётка, которую панель не даёт понизить.
 *
 * Причина конкретная: экран пользователей раздаёт роли одним и тем же
 * выпадающим списком у каждой строки, включая свою собственную. Один
 * промах — и директор панели становится менеджером, после чего вернуть
 * права можно только запросом в базу мимо приложения. Такой сценарий уже
 * случался, поэтому владелец защищён на сервере, а не в интерфейсе.
 *
 * Почта берётся из окружения, чтобы её можно было сменить без правки кода;
 * значение по умолчанию — учётка владельца этого стенда.
 */
export const PANEL_OWNER_EMAIL = String(
  process.env.PANEL_OWNER_EMAIL ?? "m.pankratov@kreonopt.ru",
).trim().toLowerCase();

export function isPanelOwner(email: unknown): boolean {
  return String(email ?? "").trim().toLowerCase() === PANEL_OWNER_EMAIL;
}
