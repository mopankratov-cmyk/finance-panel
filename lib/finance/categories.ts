const SECTION_BY_CATEGORY: ReadonlyMap<string, DdsSection> = new Map(REGISTRY);

/** Все статьи справочника в порядке разделов — для выпадающих списков. */
export const DDS_CATEGORIES: readonly string[] = REGISTRY.map(([category]) => category);

/**
 * Статьи, которые уже встречаются в данных, но в списки не предлагаются:
 * старые написания и грубые статьи импорта календаря РИО. Раздел им нужен,
 * чтобы свод не ронял их в «Прочее»; в выпадающем списке такая статья
 * появляется только у платежа, у которого уже стоит (см. categoryOptions).
 */
const LEGACY_SECTIONS: Readonly<Record<string, DdsSection>> = {
  "Воврат кредитов и займов": "Инвестиционная",
  "Продажи на МП (требует уточнения)": "Операционная",
  "Зарплата": "Операционная",
  "Налоги": "Операционная",
  "Реклама": "Операционная",
  "Логистика": "Операционная",
  "Сервисы": "Операционная",
  "Кредиты и займы": "Финансовая",
  "Займы": "Финансовая",
};

export function isKnownCategory(category: string | null | undefined): boolean {
  return SECTION_BY_CATEGORY.has((category ?? "").trim());
}

export function sectionForCategory(category: string | null | undefined): DdsSection {
  const value = (category ?? "").trim();
  return SECTION_BY_CATEGORY.get(value) ?? LEGACY_SECTIONS[value] ?? "Прочее";
}

/**
 * Список для `<select>`: справочник плюс текущее значение платежа, если его
 * в справочнике нет. Иначе браузер, не найдя значения среди опций, выбирает
 * первую — и сохранение молча меняет статью.
 */
export function categoryOptions(current?: string | null): string[] {
  const value = (current ?? "").trim();
  return value && !SECTION_BY_CATEGORY.has(value) ? [value, ...DDS_CATEGORIES] : [...DDS_CATEGORIES];
}
