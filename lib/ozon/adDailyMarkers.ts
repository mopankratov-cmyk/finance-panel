/**
 * Служебные строки в истории рекламы по дням (`ozon_ad_daily`).
 *
 * Таблица хранит расход «кабинет × товар × день», но два факта в эту форму не
 * укладываются, а знать их нужно:
 *
 * - `-` — день собран, расхода не было. Без него пустой день невозможно
 *   отличить от несобранного, и экран показывал бы ноль как факт.
 * - `*` — сумма по кабинету за день. Ozon отдаёт её мгновенно, одним дешёвым
 *   запросом за любой период (`statistics/daily/json`), тогда как разнесение
 *   по товарам собирается асинхронными отчётами по одному в минуту и
 *   доезжает днями. Раньше мы ждали разнесения, чтобы показать хоть что-то, —
 *   и экраны месяцами стояли с нулями при полностью доступной сумме.
 *
 * Обе строки НИКОГДА не участвуют в разрезе по товарам: сложить их с
 * настоящими SKU значило бы удвоить расход.
 */

/** День собран, расхода не было. */
export const OZON_AD_EMPTY_DAY_SKU = "-";

/** Итог по кабинету за день (без разнесения по товарам). */
export const OZON_AD_CABINET_TOTAL_SKU = "*";

export function isOzonAdServiceSku(sku: unknown): boolean {
  const value = String(sku ?? "");
  return value === OZON_AD_EMPTY_DAY_SKU || value === OZON_AD_CABINET_TOTAL_SKU;
}

export function isOzonAdCabinetTotalSku(sku: unknown): boolean {
  return String(sku ?? "") === OZON_AD_CABINET_TOTAL_SKU;
}
