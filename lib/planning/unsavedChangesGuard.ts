/**
 * Общий предохранитель от тихой потери несохранённых правок при переключении
 * кабинета из глобального переключателя в шапке (WbCabinetSwitcher /
 * OzonCabinetSwitcher — они живут в layout-shell, а не на самом экране плана,
 * поэтому проверить «есть ли несохранённые правки» на месте переключения
 * нечем). План продаж на WB/Ozon (components/planning/SalesPlanPage.tsx) —
 * единственный, кто сейчас регистрирует здесь проверку: пока черновик месяца
 * не сохранён или автосохранение зависло в ошибке, переключатель обязан
 * спросить подтверждение, а не молча стереть правки при смене кабинета.
 *
 * Синглтон на всё приложение и это осознанно: активный экран регистрирует
 * свою проверку на время жизни компонента (useEffect с cleanup), а для всех
 * остальных экранов guard === null и переключатель работает как раньше.
 */
let guard: (() => boolean) | null = null;

export function setUnsavedChangesGuard(nextGuard: (() => boolean) | null) {
  guard = nextGuard;
}

/** true — можно переключать; false — пользователь отменил переключение. */
export function confirmDiscardUnsavedChanges(): boolean {
  return guard ? guard() : true;
}
