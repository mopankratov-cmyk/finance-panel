/**
 * Кому можно дёргать синхронизацию руками, помимо крона.
 *
 * Список вынесен из `helpers.ts` отдельно и НАРОЧНО без импортов из
 * `next/server`: то же правило нужно кнопке в браузере. Пока правда жила
 * только на сервере, «Прогнать РК» на /wb/rk была активна для менеджера МП и
 * для внешнего селлера — а роут отвечал им голым английским «Unauthorized»
 * (селлеру — и вовсе сообщением про WB-аналитику в ответ на кнопку
 * синхронизации). Менеджер МП открывает журнал каждый день, то есть каждый
 * день видел живую кнопку, которая не работает.
 *
 * Почему список именно такой: прогон только читает у маркетплейса и пишет в
 * нашу базу — необратимого здесь нет, — но он нагружает лимиты токенов
 * кабинета, и решать, когда их тратить, дело владельца.
 */
export const MANUAL_RUN_ROLES = ["director", "finance"] as const;

export function canRunSyncManually(role: string | null | undefined): boolean {
  return !!role && (MANUAL_RUN_ROLES as readonly string[]).includes(role);
}
