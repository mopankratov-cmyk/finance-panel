/**
 * Ключ проведения документа — один на нажатие кнопки.
 *
 * Генерируется на клиенте перед отправкой и повторяется при ретрае того же
 * нажатия. Сервер по нему отличает «второй клик» от «вторая отгрузка».
 */
export const newDocKey = (): string =>
  typeof crypto !== "undefined" && "randomUUID" in crypto
    ? crypto.randomUUID()
    // Старые webview без randomUUID: ключ всё равно должен быть уникальным,
    // иначе защита превратится в блокировку второй настоящей операции.
    : `k-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 10)}`;
