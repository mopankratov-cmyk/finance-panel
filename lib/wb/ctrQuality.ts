/**
 * Порог достоверности CTR.
 *
 * CTR — доля, и на маленьком знаменателе она перестаёт что-либо значить:
 * один показ и один клик дают «100%», три показа и два клика — «66,7%».
 * Арифметика верна, сигнала нет.
 *
 * Порог подобран по живым данным кабинета СЛОЁНО (1702 клетки, 23.08.2026):
 *
 *   порог   скрыто клеток   осталось CTR > 10%   максимум CTR
 *     30        44,9%              2                 15,6%
 *     50        47,4%              0                  9,3%
 *    100        49,5%              0                  9,3%
 *
 * На 50 показах аномалии выше 10% исчезают полностью, а ужесточать дальше
 * бессмысленно: максимум тот же, зато прячется больше живых клеток.
 *
 * Важно: прячем ДОЛЮ, а не факт. Показы и клики остаются видны в разборе по
 * кампаниям — иначе получилось бы, что данных нет, хотя они есть.
 */
export const CTR_MIN_VIEWS = 50;

/** Доля клика, если знаменатель достаточен; иначе null — «мерить нечем». */
export function reliableCtr(views: number, clicks: number): number | null {
  if (!Number.isFinite(views) || views < CTR_MIN_VIEWS) return null;
  return (clicks / views) * 100;
}
