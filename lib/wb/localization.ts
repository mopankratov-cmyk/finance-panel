const norm = (s: string) => (s || "").toLowerCase().trim();
const lookup = (table: [string, Okrug][], v: string): Okrug | null => {
  const n = norm(v);
  for (const [key, ok] of table) if (n.includes(key)) return ok;
  return null;
};
export const regionOkrug = (region: string) => lookup(REGION_OKRUG, region);
export const warehouseOkrug = (wh: string) => lookup(WAREHOUSE_OKRUG, wh);

// ИРП (КРП) % по доле локализации (таблица WB): чем выше локализация — тем ниже надбавка, ≥60% → 0.
export function irpByLocalization(pct: number): number {
  if (pct >= 60) return 0;
  // якоря из публикации WB: 0%→2.50, 5%→2.45, 10%→2.35, … 55–60%→2.00
  const bands: [number, number][] = [
    [5, 2.5], [10, 2.45], [15, 2.35], [20, 2.3], [25, 2.25], [30, 2.2],
    [35, 2.15], [40, 2.12], [45, 2.08], [50, 2.05], [55, 2.02], [60, 2.0],
  ];
  for (const [hi, irp] of bands) if (pct < hi) return irp;
  return 2.0;
}

// ИЛ (индекс локализации) — множитель логистики. Точный ИЛ = взвешенный КТР (per-order, нет в API),
// поэтому ОЦЕНКА из доли локализации: 0% лок → ~2.0, 100% лок → ~1.0 (ниже = дешевле).
export function ilEstimate(pct: number): number {
  return Math.round((2.0 - (pct / 100) * 1.0) * 100) / 100;
}

export interface OkrugStat {
  okrug: Okrug;
  orders: number;
  local: number;
  localPct: number;
  /** сколько заказов стали бы локальными, если отгрузить в этот округ (потенциал) */
  potential: number;
  hub: string;
  hasStock: boolean;
}

export interface LocalizationResult {
  localizationPct: number;
  il: number;
  irp: number;
  totalOrders: number;
  localOrders: number;
  byOkrug: OkrugStat[];
  recommendations: OkrugStat[];
  unmappedRegions: string[];
  unmappedWarehouses: string[];
}

export function computeLocalization(
  orders: { region: string | null; warehouse: string | null }[],
  stockOkrugs: Set<Okrug>,
): LocalizationResult {
  const byOkrug = new Map<Okrug, { orders: number; local: number }>();
  let total = 0, local = 0;
  const unmappedR = new Set<string>(), unmappedW = new Set<string>();

  for (const o of orders) {
    const ro = regionOkrug(o.region || "");
    const wo = warehouseOkrug(o.warehouse || "");
    if (!ro) { if (o.region) unmappedR.add(o.region); continue; }
    if (!wo && o.warehouse) unmappedW.add(o.warehouse);
    total++;
    const isLocal = ro === wo;
    if (isLocal) local++;
    const e = byOkrug.get(ro) ?? { orders: 0, local: 0 };
    e.orders++; if (isLocal) e.local++;
    byOkrug.set(ro, e);
  }

  const localizationPct = total > 0 ? Math.round((local / total) * 1000) / 10 : 0;
  const stats: OkrugStat[] = [...byOkrug.entries()].map(([okrug, e]) => ({
    okrug,
    orders: e.orders,
    local: e.local,
    localPct: e.orders > 0 ? Math.round((e.local / e.orders) * 1000) / 10 : 0,
    potential: e.orders - e.local, // нелокальные заказы этого округа = потенциал
    hub: HUB_BY_OKRUG[okrug],
    hasStock: stockOkrugs.has(okrug),
  })).sort((a, b) => b.orders - a.orders);

  // рекомендации: округа с наибольшим потенциалом, куда ещё НЕ грузим (или грузим мало)
  const recommendations = stats
    .filter((s) => s.potential > 0)
    .sort((a, b) => b.potential - a.potential)
    .slice(0, 6);

  return {
    localizationPct,
    il: ilEstimate(localizationPct),
    irp: irpByLocalization(localizationPct),
    totalOrders: total,
    localOrders: local,
    byOkrug: stats,
    recommendations,
    unmappedRegions: [...unmappedR].slice(0, 30),
    unmappedWarehouses: [...unmappedW].slice(0, 30),
  };
}
