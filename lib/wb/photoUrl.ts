interface WbRawPhoto {
  hq?: string;
  big?: string;
  c516x688?: string;
  c246x328?: string;
}

/**
 * Какую из шести ссылок WB брать как «большое фото».
 *
 * Долго бралась `hq` (1800×2400) — она вдвое крупнее `big` и логично выглядит
 * лучшим выбором. Замер 05.09.2026 по двадцати карточкам показал обратное:
 * **у девятнадцати из двадцати `hq` отдаёт 404**, а тот же кадр через `/big/`
 * открывается всегда. То есть Content API возвращает поле, которого на CDN
 * чаще всего нет.
 *
 * Ошибка была тихой ровно потому, что миниатюры живут по третьему пути
 * (`c246x328`): в сетке превью всё выглядело целым, а наружу — в вариант
 * CTR-теста, в генерацию — уходил мёртвый адрес. Ломается не у нас, а у того,
 * кто попробует его скачать.
 *
 * Поэтому порядок: `big` (есть всегда) → `hq` (крупнее, но чаще всего пусто) →
 * миниатюра. Разрешение уступаем доступности: кадр, который не скачивается,
 * не имеет разрешения вовсе.
 */
export function wbPhotoBig(photo: WbRawPhoto): string {
  return photo.big || photo.hq || photo.c516x688 || photo.c246x328 || "";
}

export function wbPhotoThumb(photo: WbRawPhoto): string {
  return photo.c246x328 || photo.big || photo.c516x688 || photo.hq || "";
}
