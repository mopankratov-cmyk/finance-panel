/**
 * Где остаток WB реален.
 *
 * Склады по городам (Коледино, Казань, Электросталь и так далее) после пожара
 * пусты: товара там нет (владелец, 21.09.2026), а строки отчёта WB по ним —
 * фантом. Реальный остаток лежит только в строке «Склад WB» — это и FBW, и FBS.
 * Сумма по всем складам поэтому завышена; корректный остаток — только по «Склад WB».
 *
 * Название приходит от WB как «Склад WB РФ» (отчёт warehouse_remains) и как
 * «Склад WB» (прежний агрегат −999999); кириллическое «ВБ» принимается на случай
 * ручных правок. Тот же шаблон в SQL — `WB_WAREHOUSE_SQL_PATTERN`.
 */
export const isWbWarehouse = (name: string | null | undefined): boolean =>
  /^Склад\s+(WB|ВБ)/i.test(String(name ?? "").trim());

/** Тот же шаблон для Postgres (`~*`): держать в одном месте с `isWbWarehouse`. */
export const WB_WAREHOUSE_SQL_PATTERN = "^склад\\s+(wb|вб)";

/**
 * Час по Москве, на который берётся суточный остаток из снимков (не позже
 * H:59). Снимки идут каждые четыре часа (03, 07, 11, 15, 19, 23 по Москве), и
 * «последний за сутки» — снимок 23:00, то есть остаток на конец дня. Чтобы дни
 * сравнивались между собой, час фиксирован, а не плавает от запуска к запуску.
 */
export const STOCK_SNAPSHOT_HOUR_MSK = 23;
