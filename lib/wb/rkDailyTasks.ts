/**
 * Ежедневная простановка задач в журнале РК — так, как это делают руками.
 *
 * Правила выведены не из соображений о том, как надо вести рекламу, а из
 * рабочей таблицы «Показы CTR CPC»: 6 213 решений менеджеров за 120 дней
 * (21.04–26.08.2026). Сверка 12.09.2026 показала две вещи.
 *
 * ПЕРВАЯ. Прежний советчик отвечал не на тот вопрос. Он двигал ставку, а ставку
 * руками в августе меняли 26 раз из 4 401 решения (0,6%). Из 491 дня, когда
 * высказались и человек, и советчик, направление совпало ОДИН раз. Поэтому
 * ночной прогон больше не советует ставку: правила остались в rkAutoTask.ts и
 * покрыты тестами, но в журнал они не пишут.
 *
 * ВТОРАЯ. Решение почти всегда повторяет вчерашнее:
 *
 *   тот же текст задачи          67,9% пар «вчера → сегодня»
 *   та же смысловая группа       89,0%
 *   серия одинаковых решений     медиана 1 день, 90-й перцентиль 5, максимум 22
 *
 * Отсюда форма правила: по умолчанию переносим вчерашнее, а меняем только там,
 * где сменилось состояние товара. Самая частая смена группы в корпусе —
 * «бюджет → откл до отгрузки» (80 раз): товар кончился. Обратная —
 * «откл до отгрузки → бюджет/вкл» (49 раз): поставка пришла.
 *
 * Чего здесь намеренно НЕТ: подкрутки бюджета. В корпусе она есть (2000 ↔ 3000
 * — 157 переходов), но цифрами не разделяется: в дни повышения медианный ДРР
 * 1,8% и CPO 141 ₽, в дни понижения 2,4% и 187 ₽ — выборки по сотне и
 * распределения перекрываются почти целиком. Правило на таком основании было
 * бы угадыванием, выданным за расчёт.
 */

/** Что стояло по этой клетке вчера. */
export interface RkYesterdayTask {
  note: string;
  /** Кто поставил: человек или прошлый ночной прогон. */
  source: "auto" | "human";
  /**
   * Сколько дней подряд эта же задача переносится без участия человека.
   * Нужна, чтобы совет, на который никто не смотрит, не жил вечно.
   */
  carriedDays: number;
}

export interface RkDailyTaskInput {
  yesterday: RkYesterdayTask | null;
  /** Остаток товара сегодня. null — не знаем, и это не то же самое, что ноль. */
  stock: number | null;
  /** Вчера реклама по товару шла: были показы или расход. */
  advertised: boolean;
}

export interface RkDailyTask {
  note: string;
  /** Почему так. Видно рядом с задачей и попадает в разбор расхождений. */
  reason: string;
}

/** Задача «товар кончился». Первая по частоте в корпусе — 40,9% решений августа. */
export const RK_OUT_OF_STOCK_NOTE = "Откл до отгрузки";
/** Задача «поставка пришла». В корпусе после отгрузки ставят её или бюджет. */
export const RK_BACK_IN_STOCK_NOTE = "Вкл";

/**
 * Сколько дней подряд переносить задачу, к которой человек не притрагивался.
 *
 * В корпусе самая длинная серия одинаковых решений — 22 дня, 90-й перцентиль —
 * 5. Потолок в две недели заметно выше обычного и при этом не даёт совету,
 * который никто не открывал, висеть месяцами: молчание честнее, чем
 * повторение неизвестно чего.
 */
export const RK_MAX_CARRY_DAYS = 14;

/**
 * Задача на сегодня по одному товару. `null` — советовать нечего.
 *
 * Молчание здесь штатный ответ, а не отказ: в журнале сотни строк, и совет по
 * каждой превращается в шум, который выключают целиком.
 */
export function planDailyRkTask(input: RkDailyTaskInput): RkDailyTask | null {
  const { yesterday, stock } = input;

  // ── Остаток кончился ──────────────────────────────────────────────────────
  // Единственное правило, которое перебивает вчерашнее решение. Рекламировать
  // то, чего нет, нельзя ни при каком бюджете, и в корпусе это самый частый
  // переход между группами.
  if (stock === 0) {
    if (yesterday?.note.trim() === RK_OUT_OF_STOCK_NOTE) {
      return { note: RK_OUT_OF_STOCK_NOTE, reason: "Остатка по-прежнему нет — задача со вчера в силе" };
    }
    return { note: RK_OUT_OF_STOCK_NOTE, reason: "Остаток нулевой — рекламировать нечего" };
  }

  if (!yesterday || !yesterday.note.trim()) return null;

  // ── Поставка пришла ───────────────────────────────────────────────────────
  // Вчера гасили из-за остатка, сегодня он есть. Что именно включать — бюджет
  // или расписание — решает человек: в корпусе после отгрузки ставят и то и
  // другое, и угадывать за него мы не станем.
  if (yesterday.note.trim() === RK_OUT_OF_STOCK_NOTE && stock != null && stock > 0) {
    return { note: RK_BACK_IN_STOCK_NOTE, reason: `Остаток появился (${stock} шт.) — вчера реклама была выключена до отгрузки` };
  }

  // ── Совет, который никто не открывал, не живёт вечно ──────────────────────
  if (yesterday.source === "auto" && yesterday.carriedDays >= RK_MAX_CARRY_DAYS) return null;

  return {
    note: yesterday.note.trim(),
    reason: yesterday.source === "human"
      ? "Перенос вчерашнего решения"
      : `Перенос вчерашнего предложения (${yesterday.carriedDays + 1}-й день без правок)`,
  };
}

/**
 * Наш ли это совет.
 *
 * Ночной прогон переносит вчерашнее решение, и без этой проверки он тянул бы
 * за собой советы ОТМЕНЁННЫХ правил про ставку: сухой прогон 12.09.2026 честно
 * показал «Поднять ставку до 5,23 ₽ · перенос вчерашнего предложения, 2-й день».
 * Ровно то, от чего уходим, только теперь ещё и с самоподдержкой.
 *
 * Решение человека переносится всегда — это его слово. А из предложений
 * переносятся только те, что поставил этот планировщик: их причина начинается
 * с «Перенос» или «Остаток», и этот текст пишем мы сами.
 */
export function isPlannerSuggestion(reason: string | null | undefined): boolean {
  const text = String(reason ?? "").trim();
  return text.startsWith("Перенос") || text.startsWith("Остаток");
}
