-- Тип ставки кампании WB (см. app/api/sync/adverts/route.ts).
-- v2/adverts отдаёт bid_type («ручная» против «единой» ставки), но синк его
-- отбрасывал — а без типа нельзя разложить рекламные метрики по видам кампаний
-- (паритет с блоками «Реклама · Ручная / Единая» кабинета Оптимы).
--
-- Колонка NULLABLE без default: строки прежнего синка тип не знают, и любое
-- подставленное значение было бы выдумкой. Заполнится следующим прогоном
-- синка кампаний. Храним сырую строку WB, а не свой enum: новое значение на
-- стороне WB не сломает запись.

alter table public.wb_adverts add column if not exists bid_type text;

comment on column public.wb_adverts.bid_type is 'Тип ставки кампании как его отдаёт WB v2/adverts (например manual/auto). NULL — синк записал строку до появления колонки.';
