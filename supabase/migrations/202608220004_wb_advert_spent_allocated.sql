-- Расход кампании, не разнесённый WB по артикулам.
--
-- fullstats отдаёт расход дважды: суммой за день по кампании и разбивкой по
-- артикулам. Вторая регулярно неполна. Зонд sync-health?spend_split=1 на
-- проде 22.08.2026: кампания 38617401 за 22.08 потратила 569,74 ₽ на 12
-- артикулов, а по артикулу 774084816 разбивка отдала ноль — при живых
-- корзинах. По кабинету так терялось около 5% расхода (21.08: 9 985 ₽
-- собранных против 10 510 ₽ кабинетных), а на отдельной карточке — весь.
--
-- Недостающая часть раскладывается по артикулам кампании пропорционально
-- показам (см. lib/wb/advertSpendAllocation.ts) и хранится ОТДЕЛЬНО от факта
-- WB. Так в любой момент видно, сколько в цифре измерено, а сколько
-- восстановлено, и разложенную часть можно пересчитать другим правилом,
-- не потеряв исходник.

alter table public.wb_advert_nm_campaign_daily
  add column if not exists spent_allocated numeric not null default 0;
comment on column public.wb_advert_nm_campaign_daily.spent_allocated is
  'Доля расхода кампании, которую WB не разнёс по артикулам, разложенная пропорционально показам. Факт WB лежит в spent.';

-- В витрине spent — полный расход, отнесённый на артикул (факт + разложенное):
-- Воронка и РНП читают её напрямую, и им нужна полная цифра. Разложенная
-- часть продублирована отдельной колонкой ради прозрачности.
alter table public.wb_advert_nm_daily
  add column if not exists spent_allocated numeric not null default 0;
comment on column public.wb_advert_nm_daily.spent_allocated is
  'Сколько из spent восстановлено раскладкой нераспределённого расхода кампаний, а не измерено WB напрямую.';

-- Снимок журнала помнит, сколько в его расходе восстановлено: иначе через
-- месяц по зафиксированной цифре уже не понять, измерение это или раскладка.
alter table public.wb_rk_journal_daily
  add column if not exists spent_allocated numeric not null default 0;
comment on column public.wb_rk_journal_daily.spent_allocated is
  'Сколько из spent восстановлено раскладкой нераспределённого расхода кампаний на момент снимка.';
