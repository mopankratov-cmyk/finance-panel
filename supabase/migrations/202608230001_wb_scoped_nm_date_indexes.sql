-- Кабинеты с ограниченным ассортиментом: индексы под их порядок фильтров.
--
-- Замер на проде 23.08.2026 (Оптима, 18 артикулов в ассортименте, окно 7
-- дней): заказы 8 849 мс, сборочные задания 8 367 мс, продажи 5 734 мс —
-- 8.6 секунды из 10.8 всего ответа. Артикулов мало, а времени больше, чем у
-- кабинета на 467 артикулов.
--
-- Причина: такие кабинеты читают сырые строки с фильтром
-- `cabinet_id = X and nm_id in (...18 штук...) and date between ...`, а
-- существующие индексы идут в порядке (cabinet_id, date, nm_id). По ним
-- Postgres берёт весь диапазон дат кабинета — то есть все тысячи строк — и
-- лишь потом отбрасывает чужие артикулы.
--
-- Индекс с nm_id перед датой отсекает ассортимент сразу: остаётся 18 узких
-- диапазонов вместо одного широкого. Прежние индексы не трогаем — по ним
-- ходят кабинеты без ограничения ассортимента, у которых фильтра по nm нет.

create index if not exists wb_orders_cabinet_nm_date_idx
  on public.wb_orders (cabinet_id, nm_id, date);

create index if not exists wb_sales_cabinet_nm_date_idx
  on public.wb_sales (cabinet_id, nm_id, date);

-- Сборочные задания фильтруются по дате создания на стороне WB.
create index if not exists wb_fbs_orders_cabinet_nm_created_idx
  on public.wb_fbs_orders (cabinet_id, nm_id, created_at_wb);
