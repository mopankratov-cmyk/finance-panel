-- Числовой id сборочного задания рядом с srid.
--
-- Зачем: коды маркировки запрашиваются по order_id, а таблица хранит только
-- srid. Из-за этого фоновый сборщик выкачивает список заданий у WB на КАЖДОМ
-- прогоне — только чтобы узнать идентификаторы, которые уже были у нас в базе.
-- У агентских кабинетов это особенно дорого: WB отдаёт задания всего продавца
-- (у Оптимы 23.08.2026 — 3696 чужих на 304 своих), и вся эта выдача качается
-- заново каждые 15 минут.
--
-- С колонкой очередь строится прямо из базы, а WB остаётся только сам опрос
-- кодов — 100 заданий за запрос.
--
-- Колонка nullable: старые строки заполнятся сами при следующем проходе
-- синка fbs-orders, ронять их нечем и незачем.
alter table public.wb_fbs_orders
  add column if not exists order_id bigint;

-- Частичный индекс: ищем всегда «мои задания за период, у которых id известен».
create index if not exists wb_fbs_orders_order_id_idx
  on public.wb_fbs_orders (cabinet_id, order_id)
  where order_id is not null;

comment on column public.wb_fbs_orders.order_id is
  'id сборочного задания Marketplace. По нему запрашиваются коды маркировки (POST /api/marketplace/v3/orders/meta).';

-- srid в продажах: по нему возврат сопоставляется со сборочным заданием.
--
-- Зачем: экран сверки берёт возвраты живьём из статистики WB, а у неё лимит
-- один запрос в минуту на продавца — на Оптиме это стабильное «WB ограничил
-- частоту (продажи и возвраты)», и раздел возвратов просто пуст.
--
-- Продажи мы и так синкаем ежечасно, причём вместе с возвратами (saleID на
-- «R…»). Не хватало только srid — с ним возвраты читаются из своей базы, и
-- живой запрос к WB на экране больше не нужен.
alter table public.wb_sales
  add column if not exists srid text;

-- Частичный индекс только по возвратам: их доля в продажах невелика,
-- а искать мы будем именно их.
create index if not exists wb_sales_returns_srid_idx
  on public.wb_sales (cabinet_id, srid)
  where srid is not null and sale_id like 'R%';

comment on column public.wb_sales.srid is
  'srid строки продаж = rid сборочного задания Marketplace. Связывает возврат с заданием в сверке КИЗ.';
