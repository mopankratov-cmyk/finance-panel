-- Артикул и баркод сборочного задания.
--
-- Зачем: экран сверки КИЗ держит список заданий в unstable_cache — том самом
-- кэше, который НЕ общий между роутами и умирает с каждой сборкой. После
-- любого деплоя экран заново выкачивает у WB весь список: на агентском
-- кабинете это 20 000 заданий за прогон, из которых свои — 304. Отсюда и
-- «WB ограничил частоту» при обычном открытии страницы.
--
-- В базе задания уже лежат (синк fbs-orders), и лежат только свои. Не хватало
-- двух полей: баркод участвует в сопоставлении кода маркировки с товаром
-- (kizMatchesBarcode), артикул — в отображении строк. Оба приходят в том же
-- ответе WB, который синк и так читает: article и skus[0].
--
-- С ними экран читает задания из базы, а к WB ходит только за тем, чего в
-- базе быть не может.
alter table public.wb_fbs_orders
  add column if not exists article text;

alter table public.wb_fbs_orders
  add column if not exists barcode text;

comment on column public.wb_fbs_orders.article is
  'Артикул продавца из сборочного задания Marketplace.';
comment on column public.wb_fbs_orders.barcode is
  'Первый баркод задания (skus[0]). Участвует в сопоставлении кода маркировки с товаром.';
