-- Склад перестал быть собственностью кабинета ещё в 202608230005: на одном
-- фулфилменте лежит товар нескольких ИП, и остаток считается по паре
-- «склад + юрлицо». Но колонка warehouses.cabinet_id от первой редакции осталась,
-- и осталась NOT NULL — а код склады заводит без кабинета. Итог: кнопка «Создать
-- склад» падала на ограничении, и завести второй склад было невозможно.
--
-- Колонку убираем целиком, а не просто снимаем NOT NULL: её никто не читает
-- (ни функции проводок, ни stock_balances), а привязка склада к одному кабинету
-- прямо противоречит тому, как склад устроен сейчас.

alter table public.warehouses drop column if exists cabinet_id;

notify pgrst, 'reload schema';
