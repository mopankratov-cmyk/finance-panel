-- Статус «уже выведен из оборота» — ТОЛЬКО СХЕМА, без функций.
--
-- Исправление ошибки в замысле, найденной на живых данных.
--
-- Отчёт Wildberries по маркированным товарам я принял за источник списка НА
-- вывод. Это неверно: он показывает уже СОВЕРШЁННЫЕ операции с кодом — вывод из
-- оборота и возврат в оборот. Для FBW там всё, потому что маркетплейс выводит
-- сам. Для FBS там пусто ровно потому, что никто ещё не вывел, — а это и есть
-- то, что нам нужно найти.
--
-- Проверка, которая это показала: Retail Family начал продавать по FBS 21
-- августа, 131 заказ ветровок HT-83 — товара маркированного. В отчёте по
-- маркировке за те же дни нет ни одного их кода.
--
-- Отсюда правильное разделение источников:
--   отчёт по маркировке  → что УЖЕ выведено, вычитаем из списка;
--   выгрузка завершённых заказов ФБС → что продано и ждёт вывода.

alter table public.kiz_withdrawals
  drop constraint if exists kiz_withdrawals_status_check;
alter table public.kiz_withdrawals
  add constraint kiz_withdrawals_status_check
  check (status in ('sold', 'returned', 'sent', 'returned_after_sent', 'fbw', 'unknown', 'withdrawn'));

comment on column public.kiz_withdrawals.status is
  'sold — ждёт вывода; sent — отправлен тому, кто выводит; withdrawn — уже выведен по данным WB; fbw — вывел маркетплейс; returned — вернулся в оборот; unknown — схема продажи неизвестна.';

notify pgrst, 'reload schema';
