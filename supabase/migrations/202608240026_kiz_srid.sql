-- Код маркировки хранится вместе с srid — ТОЛЬКО СХЕМА, без функций.
--
-- Зачем. Код маркировки лежит в wb_fbs_order_kiz с ключом «кабинет + номер
-- сборочного задания». Чтобы понять, продан ли этот код (а выводить из оборота
-- нужно именно проданное), нужен srid — он связывает задание с продажей в
-- wb_sales. Сейчас srid приходится искать в wb_fbs_orders, и связь рвётся:
-- колонку order_id там добавили позже, и она заполнена у 9 070 заданий из
-- 22 519. На живых данных это значит, что из 152 заданий с кодами удалось
-- сопоставить с продажей только 20.
--
-- Хранить srid рядом с кодом дешевле и надёжнее: он известен в момент опроса,
-- потому что очередь заданий и строится из wb_fbs_orders, где srid — часть
-- первичного ключа.

alter table public.wb_fbs_order_kiz
  add column if not exists srid text;

create index if not exists wb_fbs_order_kiz_srid_idx
  on public.wb_fbs_order_kiz (srid);

comment on column public.wb_fbs_order_kiz.srid is
  'Идентификатор продажи: связывает код маркировки с фактом выкупа в wb_sales.';

notify pgrst, 'reload schema';
