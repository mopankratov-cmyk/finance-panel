-- Реестр кодов маркировки подчиняется юрлицу — ЧАСТЬ 1 из 2: схема.
--
-- В этом файле НЕТ ни одной функции. Процедуры — в 202608250031.
--
-- Повод. Токен Честного Знака принадлежит ИП или ООО, а не кабинету
-- маркетплейса. Реестр же знал только кабинет — и число «столько-то кодов ждут
-- вывода» было одним и тем же для всех девяти юрлиц: сколько ни переключай
-- селектор, ответ не менялся, хотя весь остальной ряд на экране менялся.
--
-- Почему колонка, а не соединение по кабинету на чтении:
--
-- 1. Связь «кабинет — юрлицо» многие-ко-многим. Агентский кабинет Оптимы связан
--    сразу с двумя юрлицами, и соединение по нему размножило бы строку: сумма по
--    вкладкам превысила бы общее число, а фильтр перестал бы быть разбиением.
-- 2. Владельца кода определяет ИНН, под которым код выпущен. Это факт кода, а не
--    вычисляемое поле: кабинет могут пересоздать, связь перевесить, товар
--    передать — реестр уже отправленных кодов от этого меняться не должен.
-- 3. Главный случай тут — как раз агентский. Коды NORVIA, проданные через
--    кабинет Оптимы, принадлежат ИП, чей это товар; у самого кабинета
--    собственного юрлица нет вовсе, и «по кабинету» они остались бы ничьими.

alter table public.kiz_withdrawals
  add column if not exists legal_entity_id uuid references public.legal_entities(id) on delete restrict;

comment on column public.kiz_withdrawals.legal_entity_id is
  'Юрлицо — владелец кода: чей товар, а при неизвестном товаре — чей собственный кабинет. null означает «не установлено», и такие коды показываются отдельно, а не приписываются кому-то.';

-- Все запросы вкладки идут «юрлицо + статус (+ дата продажи)»: сводка, срок,
-- сбор файла.
create index if not exists kiz_withdrawals_entity_status_idx
  on public.kiz_withdrawals (legal_entity_id, status, sold_at);

