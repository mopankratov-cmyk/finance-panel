-- Индекс по времени снимка в истории остатков.
--
-- Ночная чистка (app/api/sync/stocks-history-cleanup) падала по statement
-- timeout четыре ночи подряд — 28…31.08.2026, — и удалять при этом было
-- НЕЧЕГО: строк старше 90 дней в таблице нет вовсе. Валил её масштаб:
-- 1 419 252 строки и ни одного индекса по snapshot_at, поэтому условие
-- `snapshot_at < cutoff` читает таблицу целиком. Замер 01.09.2026: обычная
-- выборка с limit 1 по этому условию — 2,4 секунды; удаление по всему
-- диапазону с точным пересчётом строк не укладывалось в лимит вовсе.
--
-- Сама чистка уже переписана на пачки и в лимит теперь укладывается, но без
-- индекса каждая ночь всё равно означает полный проход по 1,4 млн строк — и
-- дальше только хуже: таблица растёт снимком каждые четыре часа.
--
-- CONCURRENTLY — чтобы не блокировать запись: в эту таблицу пишет крон
-- stocks-history. ВАЖНО: такой оператор нельзя выполнять внутри транзакции.
-- В SQL-редакторе Supabase выполнять его ОТДЕЛЬНО, одним запросом.

create index concurrently if not exists wb_stocks_history_snapshot_at_idx
  on public.wb_stocks_history (snapshot_at);

comment on index public.wb_stocks_history_snapshot_at_idx is
  'Для чистки истории старше RETENTION_DAYS: без него удаление сканирует всю таблицу.';
