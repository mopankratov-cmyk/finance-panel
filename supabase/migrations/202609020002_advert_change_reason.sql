-- Причина действия, записанная человеком в момент действия.
--
-- Журнал модуля отвечает на «что, кто и когда», но не на «почему» — а наёмный
-- менеджер по рекламе обязан объяснять владельцу каждое своё вмешательство.
-- Забавно, что у автомата с этим лучше: автоправило пишет причину решения
-- («ДРР 25% выше цели 15% → 500 → 450»), а человек такой возможности не имел.
--
-- Восстановить причину задним числом нельзя. Экономика кампании считается на
-- скользящем окне в четырнадцать дней, и через неделю у той же кампании другие
-- ДРР и точка безубыточности: цифры, по которым принималось решение, к моменту
-- разбора уже не воспроизводятся.
--
-- Поле необязательное. Обязательность, которую закрывает значение по умолчанию,
-- обязательностью не является: человек нажал бы «Подтвердить», а в аудите
-- осталась бы фраза панели, подписанная его именем. Совет алгоритма, если его
-- показывать, живёт отдельно — тем же приёмом, что и в задачах журнала РК, где
-- suggested_note хранится рядом с note и не затирается правкой. Ценность именно
-- в расхождении между тем, что предложила панель, и тем, что сделал человек.

alter table public.advert_bid_changes
  add column if not exists reason text;

comment on column public.advert_bid_changes.reason is
  'Причина действия словами человека. Пусто — не объяснял; заполняется только вручную, панель сюда своих формулировок не пишет.';
