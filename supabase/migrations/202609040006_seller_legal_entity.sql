-- Внешний селлер ведёт свой склад: юрлицо для его кабинета.
--
-- Модуль склада считает всё по юрлицу: остаток, себестоимость, документы,
-- события. Доступ к юрлицу выводится из кабинетов — внешнему селлеру видны
-- только те, что принадлежат его организации (lib/warehouse/entityAccess.ts).
-- Значит, чтобы открыть ему модуль, юрлицо у него должно быть своё: тогда он
-- работает в нём и физически не может увидеть чужие строки — их отсекает тот
-- же фильтр, что и на всех остальных экранах.
--
-- Кабинет цепляется по ИНН, как и у наших юрлиц в 202608230004. Связь own:
-- селлер продаёт через свой кабинет сам, агентской схемы здесь нет.
--
-- Это не «наше» юрлицо: товар, деньги и склад принадлежат чужой компании, и в
-- отчётности группы оно не участвует. Оно нужно ровно как ось изоляции.

