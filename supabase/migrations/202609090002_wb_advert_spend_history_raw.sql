-- артикул товара прямо в тексте, например "куртка NV-816-04") не
-- подтверждено вживую: имя JSON-поля в ответе WB adv/v1/upd угадано, и
-- первый прогон на проде вернул его пустым для всех строк. raw хранит
-- сырой ответ WB на строку — по нему можно один раз посмотреть реальное имя
-- поля и поправить парсинг без гадания.
alter table public.wb_advert_spend_history
  add column if not exists raw jsonb;

