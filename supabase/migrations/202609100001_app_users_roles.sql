-- Несколько ролей у одного сотрудника.
--
-- Решение владельца от 09.09.2026 по ТЗ о правах: человек, ведущий оба
-- маркетплейса, получает ОБЕ роли менеджера, а не третью «менеджер МП». Так
-- набор прав остаётся суммой понятных ролей, и не приходится заводить роль на
-- каждое сочетание — иначе их станет больше, чем людей.
--
-- Колонка `role` остаётся: по ней выбирается стартовый экран и ею подписан
-- журнал, а главное — подписанная сессия живёт неделю, и человек с прежней
-- кукой не должен вылететь при выкладке. Код читает `roles`, а когда их нет —
-- одну `role` (lib/auth/session.ts, sessionRoles).
--
-- Пока миграция не применена, панель работает как прежде: и вход, и форма
-- сотрудника ловят ошибку «нет такой колонки» и спускаются на одну роль.
alter table public.app_users
  add column if not exists roles text[];

-- Уже заведённым сотрудникам их единственная роль переносится в список, чтобы
-- два поля не разошлись с первого дня.
update public.app_users
   set roles = array[role]
 where roles is null
   and role is not null;

comment on column public.app_users.roles is
  'Все роли сотрудника. Права складываются: действие разрешено, если его разрешает хотя бы одна роль. Внешние роли (seller, seller_owner) не смешиваются с внутренними — это проверяет app/api/users/route.ts.';

notify pgrst, 'reload schema';
