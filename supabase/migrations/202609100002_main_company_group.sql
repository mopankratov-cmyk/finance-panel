-- Одна группа для РИО, ИП Панкратова, ИП Кучеренко и ИП Митриченко.
-- Историческую техническую строку не удаляем: у неё могут быть уже созданные
-- платежи. Отключаем её, чтобы она больше не появлялась в списках выбора.
update public.companies
set group_name = 'Основная группа'
where name in ('ООО РИО', 'ИП Панкратов', 'ИП Кучеренко', 'ИП Митриченко');

update public.companies
set is_active = false
where name = 'Общая группа РИО';
