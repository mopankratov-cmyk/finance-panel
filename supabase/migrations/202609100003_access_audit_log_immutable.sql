-- Журнал действий делается неизменяемым по-настоящему.
--
-- В миграции 202609100002 стояло `grant select, insert ... to service_role`, и
-- я записал в комментарии, что удалять записи не может никто. Живая проверка
-- это опровергла: сервисная роль спокойно удалила и переписала строки.
--
-- Причина в том, что GRANT только ДОБАВЛЯЕТ права. Supabase раздаёт
-- service_role полный набор на новые таблицы схемы public через default
-- privileges, и мой grant ничего не отнял — он продублировал часть уже
-- выданного. Отзывать надо явно, и именно у той роли, под которой ходит
-- приложение: anon и authenticated тут ни при чём, панель ходит сервисной.
--
-- §17 ТЗ: «Пользователь не должен иметь возможность удалить историю
-- собственных действий». Самый надёжный способ это удержать — чтобы права на
-- удаление не было ни у кого, включая приложение. Панели оно и не нужно:
-- журнал только пишется и читается.
revoke all on table public.access_audit_log from service_role;
revoke all on table public.access_audit_log from anon, authenticated;

grant select, insert on table public.access_audit_log to service_role;

-- Права на последовательность идентификатора: без них insert упрётся в отказ
-- при выдаче номера, и журнал перестанет писаться вовсе.
grant usage, select on all sequences in schema public to service_role;

-- Правка задним числом закрывается тем же способом, что и удаление: UPDATE
-- сервисной роли не выдан. Отдельная защита не нужна — нет права, нет и
-- вопроса, кто его применил.

-- Комментарий таблицы уже лежит в базе с прежним обещанием — переписываем его
-- вместе с правами, иначе схема продолжит утверждать то, чего не было.
comment on table public.access_audit_log is
  'Журнал действий по ТЗ о правах §17: входы, учётные записи и роли, зарплата, себестоимость, цены, рекламные бюджеты, поставки, финансовые отчёты и классификация, складские операции, выгрузки. Приложению выданы только select и insert: удалять и править записи не может даже сервисная роль.';

notify pgrst, 'reload schema';
