-- Модули внешнего контура.
--
-- Решение владельца: у клиента-селлера свой главный пользователь, и он сам
-- раздаёт доступ СВОИМ сотрудникам — по модулям. Клиенту открыты ровно три:
-- Wildberries, Ozon и Склад. Внутренних разделов компании — финансов,
-- зарплаты, закупок, учётных записей — во внешнем контуре нет вовсе.
--
-- Пустой список означает «все три», а НЕ «ни одного». У заведённых учёток
-- клиентов модулей не проставляли, и прочитать пустоту как запрет значило бы
-- отключить живых людей в день выкладки. Ограничение включается тем, что
-- главный пользователь перечислит модули явно.
--
-- Колонка нужна только внешнему контуру: внутренних сотрудников ограничивают
-- роль и карта прав, а третьей оси ТЗ для них не просило.
alter table public.app_users
  add column if not exists modules text[];

comment on column public.app_users.modules is
  'Модули внешнего контура: wb, ozon, warehouse. Пусто — открыты все три. У внутренних ролей не используется.';

notify pgrst, 'reload schema';
