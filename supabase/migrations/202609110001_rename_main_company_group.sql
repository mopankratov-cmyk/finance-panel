-- Техническая запись была показана как «Общая группа РИО».
-- Это не отдельная группа: сохраняем её id и историю платежей, меняя только
-- понятную пользователю подпись и возвращая запись в активный список.
update public.companies
set name = 'Основная группа', group_name = 'Основная группа', is_active = true
where name = 'Общая группа РИО';
