-- Инсайты AI-агента не привязаны к кабинету — межарендная утечка (аудит P0).
--
-- agent_insights писался и читался вообще без разреза: GET /api/agent/insights
-- отдавал ВСЕ строки любой сессии с analytics.view, а вставка (два места в
-- app/api/agent/route.ts, плюс app/api/signals/route.ts и rules-движок в
-- app/api/agent/insights/generate/route.ts) ни разу не проставляла, к какому
-- кабинету относится инсайт — хотя cabinet_id к моменту вставки уже проверен
-- через hasCabinetAccess() в трёх из четырёх мест. Внешний seller_owner любой
-- организации-клиента видел темп заказов, остаток, оборачиваемость, расход
-- рекламы и ДРР чужих кабинетов и чужих организаций одним GET-запросом.
--
-- Колонки одной organization_id не хватает: инсайт может быть общим для всей
-- компании (rules-движок гоняет по rnp_report сразу по всем кабинетам, и не
-- каждая строка такой сводки резолвится в один SKU), и не каждый внутренний
-- инсайт стоит привязывать к кабинету вовсе. Поэтому cabinet_id остаётся
-- NULLABLE осознанно: NULL значит «внутренний, общий по компании» и не должен
-- становиться видимым внешнему контуру ни при каких условиях — фильтрация на
-- чтении (app/api/agent/insights/route.ts) обязана трактовать
-- «cabinet_id is null» именно так, а не как «фильтра нет».
--
-- Организация отдельной колонкой не нужна: граница организации уже целиком
-- решается через hasCabinetAccess(cabinet_id) — она сама резолвит
-- wb_cabinets.organization_id при чтении. Дублировать её здесь значило бы
-- держать вторую копию границы, которая может разойтись с первой.
alter table public.agent_insights
  add column if not exists cabinet_id uuid;

comment on column public.agent_insights.cabinet_id is
  'Кабинет, к которому относится инсайт. NULL = общий по компании инсайт (виден только внутренним ролям, никогда — внешнему контуру). Проверка владения — через hasCabinetAccess(cabinet_id), не через отдельную organization_id.';

-- Существующие строки, накопленные до этой миграции, остаются с cabinet_id
-- IS NULL — они трактуются как «внутренние, общая сводка» кодом читающего
-- роута и никогда не станут видны внешнему контуру задним числом.

create index if not exists agent_insights_cabinet_idx on public.agent_insights (cabinet_id, created_at desc);

notify pgrst, 'reload schema';
