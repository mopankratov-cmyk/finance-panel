-- Смена пароля не отзывала уже выданные сессии (аудит P1).
--
-- app/api/auth/password/route.ts переписывал password_hash, но подписанная
-- кука fp_session живёт семь дней и ничем не привязана к паролю: украденный
-- или оставленный в общем браузере токен продолжал открывать панель ещё
-- неделю ПОСЛЕ того, как человек сменил пароль именно потому, что заподозрил
-- утечку.
--
-- NULL у существующих строк — сознательно: миграция не должна мгновенно
-- разлогинить всех живых пользователей в момент применения. Проверка в
-- lib/auth/server.ts трактует NULL как «дата смены неизвестна» и не отзывает
-- сессию; отзыв начинает работать только для тех, кто сменит пароль ПОСЛЕ
-- этой миграции.
alter table public.app_users
  add column if not exists password_changed_at timestamptz;

comment on column public.app_users.password_changed_at is
  'Момент последней смены пароля. Сессии (JWT), выпущенные РАНЬШЕ этой отметки, отклоняются в getServerSession — так смена пароля отзывает уже выданные токены. NULL = отметки ещё не было, отзыва нет.';

notify pgrst, 'reload schema';
