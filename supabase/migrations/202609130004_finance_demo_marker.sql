-- «Удалить демо-данные» (DELETE app/api/finance/import/route.ts) находило
-- демо-счета ПО ИМЕНИ ("WB Счёт 1/2", "Ozon", "Банковский счёт", "Наличные"),
-- а демо-платежи на них — по ОТСУТСТВИЮ меток (import_source IS NULL AND
-- company_id IS NULL). Это отрицательный признак, а не положительный: ровно
-- эти же названия счетов естественно заводит живой пользователь, а платёж,
-- добавленный руками без указания компании и не пришедший из импорта/выписки,
-- выглядит точно так же, как демо-строка. Один клик по кнопке «Удалить демо»
-- необратимо стирал боевые деньги, если они просто совпали по форме с посевом.
--
-- Правило: демо-строка — это то, что реально вставил lib/finance/dbServer.ts
-- seed() при первом заполнении пустой панели, и ничего больше. Помечаем это
-- явно в момент посева, а не угадываем постфактум по отсутствию полей.

alter table public.accounts
  add column if not exists is_demo boolean not null default false;

alter table public.payments
  add column if not exists is_demo boolean not null default false;

comment on column public.accounts.is_demo is
  'true только у строк, вставленных lib/finance/dbServer.ts seed() при первом заполнении. Единственный источник истины для «Удалить демо-данные» — не угадывать по имени счёта.';
comment on column public.payments.is_demo is
  'true только у строк, вставленных lib/finance/dbServer.ts seed() при первом заполнении. Единственный источник истины для «Удалить демо-данные» — не угадывать по отсутствию import_source/company_id.';

-- Существующие базы уже могли быть засеяны до этой миграции — то есть в них
-- прямо сейчас лежат демо-строки с is_demo = false (столбца ещё не было).
-- Разметить их постфактум надёжно нельзя (это и есть тот самый угадывающий
-- heuristic, который мы убираем) — их придётся один раз почистить вручную,
-- если нужно, зная свои реальные счета/платежи. Новые посевы после этой
-- миграции метку получают всегда — код обновлён вместе с миграцией
-- (lib/finance/dbServer.ts).

notify pgrst, 'reload schema';
