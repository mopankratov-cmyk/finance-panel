-- Закрытие периода (§5.2 пайплайна закупок): дата на юрлице, а не на
-- складе или кабинете — тот же choice владельца, что уже стоял в задаче.
-- «Закрыто по <дате>» = последний день закрытого периода включительно;
-- null — период никогда не закрывали, проводки не ограничены.
--
-- Только колонка — сам запрет проводок живёт в отдельном триггере
-- (202609150002), тело триггерной функции с DDL в одном файле путает
-- редактор Supabase (та же причина, что развела DDL и RPC во всём этом
-- контуре).

alter table public.legal_entities
  add column if not exists period_closed_through date;

comment on column public.legal_entities.period_closed_through is
  'Проводки в stock_moves с occurred_at на эту дату или раньше запрещены триггером stock_moves_period_guard. null — период не закрывали.';
