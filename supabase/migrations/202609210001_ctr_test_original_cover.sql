-- Исходная обложка CTR-теста: где лежит её копия и вернули ли мы её на витрину.
--
-- Автосмена (app/api/ctrtest/rotate) кладёт в карточку WB фото вариантов и до
-- сих пор НЕ возвращала исходное. Возвращать было нечем: «Текущее фото» хранилось
-- ссылкой `basket-NN.wbbasket.ru/…/images/big/1.webp`, а это адрес ПОЗИЦИИ
-- карточки, а не файла — после замены обложки тот же адрес отдаёт уже
-- подставленный вариант. Поле `photos_original` (202609050001) хранит такие же
-- позиционные адреса и вернуть оригинал не могло.
--
-- Теперь на старте теста панель кладёт копию обложки в наш бакет и записывает
-- её адрес сюда. Копия — обычный файл в нашем хранилище, он не меняется.
--
--   original_cover_url — закреплённая копия обложки, стоявшей на витрине в
--                        момент запуска теста. null у тестов, созданных до
--                        этой миграции: у них оригинал уже потерян.
--   cover_swapped_at   — когда крон впервые записал в карточку вариант. Пока
--                        null, витрина не менялась, и возвращать нечего.
--   cover_restored_at  — когда исходная обложка вернулась на витрину. Крон
--                        повторяет возврат каждые пять минут, пока не заполнено.

alter table public.ctr_tests
  add column if not exists original_cover_url text,
  add column if not exists cover_swapped_at timestamptz,
  add column if not exists cover_restored_at timestamptz;

comment on column public.ctr_tests.original_cover_url is
  'Закреплённая копия обложки, стоявшей на витрине к старту теста (наш бакет). Возвращается в карточку при завершении теста.';
comment on column public.ctr_tests.cover_swapped_at is
  'Когда крон впервые записал в карточку вариант теста. null — витрина не менялась.';
comment on column public.ctr_tests.cover_restored_at is
  'Когда исходная обложка вернулась на витрину. null при заполненном cover_swapped_at — возврат ещё ждёт.';
