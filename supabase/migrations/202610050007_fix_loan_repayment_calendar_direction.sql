-- Погашение кредита и процентов — выбытие денег. Ранние ручные/текстовые
-- правки могли сохранить эти плановые строки со знаком «плюс», из-за чего
-- календарь показывал их среди поступлений и завышал остаток. Факты ДДС
-- не трогаем: исправляем только открытый план.

update public.payments
set amount = -abs(amount),
    type = 'expense'
where status = 'planned'
  and amount > 0
  and btrim(category) in (
    'Оплаты по кредитам и займам',
    'Оплата % по кредиту',
    'Погашение тела кредита',
    'Проценты по кредитам и займам',
    'Пени и штрафы по кредитам и займам',
    'Штрафы по кредитам и займам'
  );

-- Старое зеркало используется Telegram-интеграцией. Оно не является
-- источником календаря, но не должно расходиться с каноническими платежами.
do $$
begin
  if to_regclass('public.finance_payments') is not null then
    update public.finance_payments
    set amount = -abs(amount),
        type = 'expense',
        updated_at = now()
    where status = 'planned'
      and amount > 0
      and btrim(category) in (
        'Оплаты по кредитам и займам',
        'Оплата % по кредиту',
        'Погашение тела кредита',
        'Проценты по кредитам и займам',
        'Пени и штрафы по кредитам и займам',
        'Штрафы по кредитам и займам'
      );
  end if;
end $$;
