-- «Разработка ассортимента», слой наблюдений: пометка части раздела в журнале прогонов.
--
-- С 06.10 (решение владельца) у Zara и Uniqlo есть части разделов — отдельные
-- выборки того же раздела: Zara CHAQUETA без трикотажа и коллаборации Uniqlo.
-- Прогон части — не весь раздел и не верх выдачи. Без пометки «История
-- наблюдений» брала прогон части последним прогоном источника (он идёт после
-- основного) и прятала «последний оборван» у основного, а счётчик «по верху
-- выдачи» считал части окном выдачи.
--
-- Код переживает отсутствие колонки: основные прогоны её не пишут вовсе, прогон
-- части без неё пишется как раньше (без пометки), чтение журнала обходится без неё.
-- Только добавляет колонку; данных не меняет. Цен здесь нет.

alter table public.assortment_run
  add column if not exists part text;

comment on column public.assortment_run.part is
  'Часть раздела (zara_chaqueta, uniqlo_collab): отдельная выборка того же раздела; NULL — основной прогон.';
